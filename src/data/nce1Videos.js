for (const [page, title] of parts) {
  const lessonIds = title.match(/^[\d +]+/)[0].match(/\d{3}/g).map(Number)
  for (const lessonId of lessonIds) {
    if (!videosByLesson.has(lessonId)) videosByLesson.set(lessonId, [])
    videosByLesson.get(lessonId).push({ provider: 'bilibili', id: 'BV1xa411J7jJ', page, title })
  }
}

export function getNce1Videos(lessonId) {
  return videosByLesson.get(Number(lessonId)) || []
}

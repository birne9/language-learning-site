function stageForLesson(number) {
  if (number <= 30) return 1
  if (number <= 60) return 2
  if (number <= 80) return 3
  if (number <= 100) return 4
  if (number <= 120) return 5
  return 6
}

export const nce1Units = rawUnits.map((item, index) => {
  const id = index + 1
  const startLesson = id * 2 - 1
  return { ...item, id, startLesson, stage: stageForLesson(startLesson) }
})

function createLesson(item, offset) {
  const number = item.startLesson + offset
  const isInput = offset === 0
  return {
    id: number,
    unitId: item.id,
    stage: item.stage,
    title: item.titles[offset],
    kind: isInput ? '场景输入' : '句型操练',
    theme: item.theme,
    grammar: item.grammar,
    minutes: isInput ? 20 : 15,
    videos: getNce1Videos(number),
    objectives: isInput
      ? [`理解“${item.theme}”的基本表达。`, `掌握核心词汇，理解“${item.grammar}”。`, '能朗读原创例句，并完成简单替换。']
      : [`熟练运用“${item.theme}”相关句型。`, `通过替换练习巩固“${item.grammar}”。`, '能脱离例句完成简短口头输出。'],
    words: item.words.map(([word, meaning]) => ({ word, meaning })),
    examples: item.examples.map(([en, cn]) => ({ en, cn })),
    exercises: [
      isInput ? '词汇理解：根据中文提示说出本课核心词，再逐词朗读。' : '句型热身：朗读本课例句，用不同核心词完成替换。',
      item.tasks[offset],
      isInput ? '仿写练习：任选两个例句，替换人物、物品或时间，写出两个新句子。' : '口头输出：不看例句，用本课句型表达 30 秒并录音，回听检查语法和发音。',
    ],
    review: `能说出本课核心词，并围绕“${item.theme}”正确使用“${item.grammar}”完成至少两句表达。`,
  }
}

export const nce1Lessons = nce1Units.flatMap((item) => [createLesson(item, 0), createLesson(item, 1)])

export function findNce1Lesson(id) {
  const number = Number(id)
  return nce1Lessons.find((lesson) => lesson.id === number)
}
